# Key to be used in the CppType "extension" dictionary to use a custom type
# instead of the one generated by __str__
CPP_TYPE_CUSTOM="cpp_type_custom"   # -> string


class CppType(ABC):
    def __init__(self, includes:CppIncludesAny, extensions:ExtensionsAny):
        self.m_includes:CppIncludes = CppIncludes(includes)
        self.m_extensions:Extensions = Extensions(extensions=extensions)

    @abstractmethod
    def toString(self, containerClass:CppNameScope)->str:
        '''! Used to represent the type when printing '''
        ...

    def constInputParam(self, containerClass:CppNameScope)->str:
        '''! Returns the type to be used as input in the parameters '''
        return f'const {self.toString(containerClass=containerClass)}&'

    def declVar(self, writer:Writer, config:Config, var:str, containerClass:CppNameScope)->None:
        writer.writeRaw(f'{self.toString(containerClass=containerClass)} {var}')

    def __str__(self)->str: 
        assert(False)
        return "\n#error CALLED __str__ ON CppType\n"

    def setupModuleConfig(self, moduleConfig:CppModuleConfig)->None:
        moduleConfig.m_hppIncludes.merge(self.m_includes)

    def getAssigneableDefaultValue(self, containerClass:CppNameScope)->Optional[str]:
        '''! Returns the assignable default if none has been specified '''
        return None
    
    def getReadOnlyReturnType(self, containerClass:CppNameScope):
        return f'const {self.toString(containerClass=containerClass)}&'
    
CppTypeAny:TypeAlias = Union[CppType,CppNameScope,str]

class CppTypeSimple(CppType):
    '''! Implements a simple type like `int` or `int[n]` '''
    def __init__(self, simpleType:str, arrayPostfix:Optional[str]=None, includes:CppIncludesAny=None, extensions:ExtensionsAny = None, defaultValue:Union[str,bool,None]=None):
        super().__init__(includes=includes, extensions=extensions)
        self.m_simpleType:str = simpleType
        self.m_arrayPostfix:Optional[str] = arrayPostfix
        self.m_defaultValue:Union[str,bool,None] = defaultValue  # Use `False` to disable default generation of the default value

    def toString(self, containerClass:CppNameScope)->str:
        customType:Optional[str] = self.m_extensions.getValueOrNone(key=CPP_TYPE_CUSTOM)
        if customType is not None: return customType
        return self.m_simpleType

    def constInputParam(self, containerClass:CppNameScope)->str:
        return self.m_simpleType

    def declVar(self, writer:Writer, config:Config, var:str, containerClass:CppNameScope)->None:
        writer.writeRaw(f'{self.m_simpleType} {var}')
        if self.m_arrayPostfix is not None:
            writer.writeRaw(self.m_arrayPostfix)

    def setupModuleConfig(self, moduleConfig:CppModuleConfig)->None:
        super().setupModuleConfig(moduleConfig=moduleConfig)
        if re.search(r'^u?int([0-9]+)_t$', self.m_simpleType):
            moduleConfig.m_hppIncludes.add("cstdint", systemInclude=True)

    def getAssigneableDefaultValue(self, containerClass:CppNameScope)->Optional[str]:
        '''! Returns the assignable default if none has been specified '''
        if self.m_defaultValue is not None:
            if isinstance(self.m_defaultValue, str):
                return self.m_defaultValue
            else:
                return None
        if self.m_arrayPostfix is None:
            if self.m_simpleType == 'bool':
                return "false"
            else:
                return "0"
        return None

    def getReadOnlyReturnType(self, containerClass:CppNameScope):
        return f'{self.toString(containerClass=containerClass)}'

class CppTypeClass(CppType):
    '''! Implements a type that references a class generated by this generator '''
    def __init__(self, cppClass:CppNameScope, includes:CppIncludesAny=None, extensions:ExtensionsAny = None, reference:bool=False, const:bool=False, pointer:bool=False):
        super().__init__(includes=includes, extensions=extensions)
        self.m_cppClass:CppNameScope = cppClass
        self.m_reference:bool = reference
        self.m_const:bool = const
        self.m_pointer:bool = pointer

    def toString(self, containerClass:CppNameScope)->str:
        customType:Optional[str] = self.m_extensions.getValueOrNone(key=CPP_TYPE_CUSTOM)
        if customType is not None: return customType
        return ('const ' if self.m_const else '')+self.m_cppClass.getCppQualifiedName(containerClass)+('*' if self.m_pointer else '')+('&' if self.m_reference else '')

    def setupModuleConfig(self, moduleConfig:CppModuleConfig)->None:
        super().setupModuleConfig(moduleConfig=moduleConfig)
        classModule:Optional[CppModuleConfig] = self.m_cppClass.getCppModuleConfig()
        assert(classModule is not None)
        if moduleConfig != classModule:
            moduleConfig.includeModuleInHpp(classModule)

    def getAssigneableDefaultValue(self, containerClass:CppNameScope)->Optional[str]:
        '''! Returns the assignable default if none has been specified '''
        if isinstance(self.m_cppClass, CppEnumBase):
            return f'{self.m_cppClass.getCppQualifiedName(otherScope=containerClass)}::{self.m_cppClass.getDefaultEntry().m_enumEntryName}'
        return None


class CppTypeVector(CppType):
    '''! Implements a `std::vector` '''
    def __init__(self, containedType:CppTypeAny, includes:CppIncludesAny=None, extensions:ExtensionsAny = None):
        super().__init__(includes=includes, extensions=extensions)
        self.m_containedType:CppType = CppTypeFactory(containedType)

    def toString(self, containerClass:CppNameScope)->str:
        customType:Optional[str] = self.m_extensions.getValueOrNone(key=CPP_TYPE_CUSTOM)
        if customType is not None: return customType
        return f"std::vector<{self.m_containedType.toString(containerClass=containerClass)}>"

    def setupModuleConfig(self, moduleConfig:CppModuleConfig)->None:
        super().setupModuleConfig(moduleConfig=moduleConfig)
        moduleConfig.m_hppIncludes.add("vector", systemInclude=True)
        self.m_containedType.setupModuleConfig(moduleConfig=moduleConfig)

