from __future__ import annotations
from .py_labels import PyVisibility
from .py_namescope import PyNameScope
from metaprog.util.extensions import ExtensionsAny

class PyNameScopeExternal(PyNameScope):
    '''! Represents a name taken from an external module, i.e. not generated by PyMetaProg

    This object is mainly used to make external names (functions, classes, constants, etc.) 
    available to the generated code in a generalized way.
    '''
    def __init__(
            self, 
            nameScope:str,
            extensions:ExtensionsAny=None,
        ) -> None:
        super().__init__(nameScope=nameScope, pyIncludesAny=None, extensions=extensions, visibility=PyVisibility.PUBLIC)

    def clone(self) -> PyNameScopeExternal:
        return PyNameScopeExternal(nameScope=self.m_nameScope, extensions=self.m_extensions)

    def merge(self, toBeImported:PyNameScopeExternal) -> None:
        self.m_extensions.merge(extensions=toBeImported.m_extensions)
        self.m_pyIncludes.merge(other=toBeImported.m_pyIncludes)