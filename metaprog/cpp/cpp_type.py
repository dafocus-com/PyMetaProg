class CppTypeString(CppType):
    '''! Implements a `std::string` '''
    def __init__(self, includes:CppIncludesAny=None, extensions:ExtensionsAny = None, isConst:bool = False, isRef:bool = False, defaultValue:Optional[str]=None, isConstexpr:bool = False):
        super().__init__(includes=includes, extensions=extensions)
        self.m_isConst:bool = isConst
        self.m_isRef:bool = isRef
        self.m_defaultValue:Optional[str] = defaultValue
        self.m_isConstexpr:bool = isConstexpr

    def toString(self, containerClass:CppNameScope)->str:
        customType:Optional[str] = self.m_extensions.getValueOrNone(key=CPP_TYPE_CUSTOM)
        if customType is not None: return customType
        ret:str = ""
        if self.m_isConstexpr:
            self.m_includes.add('string_view')
            return "std::string_view"
        if self.m_isConst: ret += "const "
        ret += "std::string"
        if self.m_isRef: ret += "&"
        return ret

    def constInputParam(self, containerClass:CppNameScope)->str:
        return "const std::string_view&"

    def setupModuleConfig(self, moduleConfig:CppModuleConfig)->None:
        super().setupModuleConfig(moduleConfig=moduleConfig)
        moduleConfig.m_hppIncludes.add("string", systemInclude=True)

    def getAssigneableDefaultValue(self, containerClass:CppNameScope)->Optional[str]:
        '''! Returns the assignable default if none has been specified '''
        if self.m_defaultValue is not None:
            return f'"{strToCppStr(self.m_defaultValue)}"'
        return None

