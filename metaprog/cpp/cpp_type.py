class CppTypeSharedPtr(CppType):
    '''! Implements a `std::shared_ptr` '''
    def __init__(self, containedType:CppTypeAny, includes:CppIncludesAny=None, extensions:ExtensionsAny = None, polymorphic:bool=False, weakPointer:bool=False):
        super().__init__(includes=includes, extensions=extensions)
        self.m_containedType:CppType = CppTypeFactory(containedType)
        self.m_polymorphic:bool = polymorphic
        self.m_weakPointer: bool = weakPointer

    def toString(self, containerClass:CppNameScope)->str:
        customType:Optional[str] = self.m_extensions.getValueOrNone(key=CPP_TYPE_CUSTOM)
        if customType is not None: return customType

        ptrtype:str = "weak_ptr" if self.m_weakPointer else "shared_ptr"

        return f"std::{ptrtype}<{self.m_containedType.toString(containerClass=containerClass)}>"


    def setupModuleConfig(self, moduleConfig:CppModuleConfig)->None:
        super().setupModuleConfig(moduleConfig=moduleConfig)
        moduleConfig.m_hppIncludes.add("memory", systemInclude=True)
        self.m_containedType.setupModuleConfig(moduleConfig=moduleConfig)


def CppTypeFactory(cppTypeAny:CppTypeAny)->CppType:
    if isinstance(cppTypeAny, CppNameScope):
        return CppTypeClass(cppClass=cppTypeAny)
    elif isinstance(cppTypeAny, str):
        return CppTypeSimple(simpleType=cppTypeAny)
    else:
        assert(isinstance(cppTypeAny, CppType))
        return cppTypeAny



