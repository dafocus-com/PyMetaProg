# Key to be used in the CppType "extension" dictionary to use a custom type
# instead of the one generated by __str__
CS_TYPE_CUSTOM="cs_type_custom"   # -> string

class CsType(ABC):
    def __init__(self, usings:CsUsingsAny, extensions:ExtensionsAny):
        self.m_usings:CsUsings = CsUsings(usings)
        self.m_extensions:Extensions = Extensions(extensions=extensions)

    @abstractmethod
    def toString(self, containerClass:CsNameScope)->str:
        '''! Used to represent the type when printing '''
        ...

    def declVar(self, writer:Writer, config:Config, var:str, containerClass:CsNameScope, isRef:bool)->None:
        if isRef: 
            writer.writeRaw("ref ")
        writer.writeRaw(f'{self.toString(containerClass=containerClass)} {var}')

    def __str__(self)->str: 
        assert(False)
        return "\n#error CALLED __str__ ON CsType\n"

    def setupModuleConfig(self, moduleConfig:CsModuleConfig)->None:
        moduleConfig.m_csUsings.merge(self.m_usings)

    def getAssigneableDefaultValue(self, containerClass:CsNameScope)->Optional[str]:
        '''! Returns the assignable default if none has been specified '''
        return None
    

CsTypeAny:TypeAlias = Union[CsType,CsNameScope,str]

class CsTypeSimple(CsType):
    '''! Implements a simple type like `int` or `int[n]` '''
    def __init__(self, simpleType:str, arrayPostfix:Optional[str]=None, usings:CsUsingsAny=None, extensions:ExtensionsAny = None, nullable:bool = False, defaultValue:Union[str,bool,None]=None):
        super().__init__(usings=usings, extensions=extensions)
        self.m_simpleType:str = simpleType
        self.m_arrayPostfix:Optional[str] = arrayPostfix
        self.m_nullable:bool = nullable
        self.m_defaultValue:Union[str,bool,None] = defaultValue

    def toString(self, containerClass:CsNameScope)->str:
        suffix:str = "?" if self.m_nullable else ""
        customType:Optional[str] = self.m_extensions.getValueOrNone(key=CS_TYPE_CUSTOM)
        if customType is not None: return customType+suffix
        return self.m_simpleType+suffix

    def declVar(self, writer:Writer, config:Config, var:str, containerClass:CsNameScope, isRef:bool)->None:
        if isRef: 
            writer.writeRaw("ref ")
        suffix:str = "?" if self.m_nullable else ""
        writer.writeRaw(f'{self.m_simpleType}{suffix} {var}')
        if self.m_arrayPostfix is not None:
            writer.writeRaw(self.m_arrayPostfix)

    def getAssigneableDefaultValue(self, containerClass:CsNameScope)->Optional[str]:
        '''! Returns the assignable default if none has been specified '''
        if self.m_defaultValue is not None:
            if isinstance(self.m_defaultValue, str):
                return self.m_defaultValue
            else:
                return None
        if self.m_arrayPostfix is None:
            if self.m_simpleType=='bool':
                return "false"
            return "0"
        return None

class CsTypeClass(CsType):
    '''! Implements a type that references a class generated by this generator '''
    def __init__(self, csClass:CsNameScope, usings:CsUsingsAny=None, extensions:ExtensionsAny = None, nullable:bool = False):
        super().__init__(usings=usings, extensions=extensions)
        self.m_csClass:CsNameScope = csClass
        self.m_nullable:bool = nullable

    def toString(self, containerClass:CsNameScope)->str:
        suffix:str = "?" if self.m_nullable else ""
        customType:Optional[str] = self.m_extensions.getValueOrNone(key=CS_TYPE_CUSTOM)
        if customType is not None: return customType+suffix
        return self.m_csClass.getCsQualifiedName(containerClass)+suffix

    def setupModuleConfig(self, moduleConfig:CsModuleConfig)->None:
        super().setupModuleConfig(moduleConfig=moduleConfig)
        classModule:Optional[CsModuleConfig] = self.m_csClass.getCsModuleConfig()
        assert(classModule is not None)
        if moduleConfig != classModule:
            moduleConfig.usingModuleInCs(classModule)

    def getAssigneableDefaultValue(self, containerClass:CsNameScope)->Optional[str]:
        '''! Returns the assignable default if none has been specified '''
        if isinstance(self.m_csClass, CsEnumBase):
            return f'{self.m_csClass.getCsQualifiedName(otherScope=containerClass)}.{self.m_csClass.getDefaultEntry().m_enumEntryName}'
        return 'new()'


class CsTypeVector(CsType):
    '''! Implements a `List<...>` '''
    def __init__(self, containedType:CsTypeAny, usings:CsUsingsAny=None, extensions:ExtensionsAny = None):
        super().__init__(usings=usings, extensions=extensions)
        self.m_containedType:CsType = CsTypeFactory(containedType)

    def toString(self, containerClass:CsNameScope)->str:
        customType:Optional[str] = self.m_extensions.getValueOrNone(key=CS_TYPE_CUSTOM)
        if customType is not None: return customType
        return f"List<{self.m_containedType.toString(containerClass=containerClass)}>"

    def setupModuleConfig(self, moduleConfig:CsModuleConfig)->None:
        super().setupModuleConfig(moduleConfig=moduleConfig)
        self.m_containedType.setupModuleConfig(moduleConfig=moduleConfig)

    def getAssigneableDefaultValue(self, containerClass:CsNameScope)->Optional[str]:
        '''! Returns the assignable default if none has been specified '''
        return 'new()'

class CsTypeMap(CsType):
    '''! Implements a `SortedDictionary<...>` '''
    def __init__(self, keyType:CsTypeAny, containedType:CsTypeAny, usings:CsUsingsAny=None, extensions:ExtensionsAny = None):
        super().__init__(usings=usings, extensions=extensions)
        self.m_keyType:CsType = CsTypeFactory(keyType)
        self.m_containedType:CsType = CsTypeFactory(containedType)

    def toString(self, containerClass:CsNameScope)->str:
        customType:Optional[str] = self.m_extensions.getValueOrNone(key=CS_TYPE_CUSTOM)
        if customType is not None: return customType
        return f"SortedDictionary<{self.m_keyType.toString(containerClass=containerClass)},{self.m_containedType.toString(containerClass=containerClass)}>"

    def setupModuleConfig(self, moduleConfig:CsModuleConfig)->None:
        super().setupModuleConfig(moduleConfig=moduleConfig)
        self.m_keyType.setupModuleConfig(moduleConfig=moduleConfig)
        self.m_containedType.setupModuleConfig(moduleConfig=moduleConfig)

    def getAssigneableDefaultValue(self, containerClass:CsNameScope)->Optional[str]:
        '''! Returns the assignable default if none has been specified '''
        return 'new()'

class CsTypeString(CsType):
    '''! Implements a `string` '''
    def __init__(self, usings:CsUsingsAny=None, extensions:ExtensionsAny = None, defaultValue:Optional[str]=None):
        super().__init__(usings=usings, extensions=extensions)
        self.m_defaultValue:Optional[str] = defaultValue

    def toString(self, containerClass:CsNameScope)->str:
        customType:Optional[str] = self.m_extensions.getValueOrNone(key=CS_TYPE_CUSTOM)
        if customType is not None: return customType
        return f"string"

    def getAssigneableDefaultValue(self, containerClass:CsNameScope)->Optional[str]:
        '''! Returns the assignable default if none has been specified '''
        if self.m_defaultValue is not None:
            return f'"{strToCsStr(self.m_defaultValue)}"'
        return '""'

def CsTypeFactory(csTypeAny:CsTypeAny)->CsType:
    if isinstance(csTypeAny, CsNameScope):
        return CsTypeClass(csClass=csTypeAny)
    elif isinstance(csTypeAny, str):
        return CsTypeSimple(simpleType=csTypeAny)
    else:
        assert(isinstance(csTypeAny, CsType))
        return csTypeAny



