# Key to be used in the CppType "extension" dictionary to use a custom type
# instead of the one generated by __str__
PY_TYPE_CUSTOM="py_type_custom"   # -> string

class PyType(ABC):
    '''! In Python, types are manage the `typing` type hints '''
    def __init__(self, pyIncludesAny:PyIncludesAny, extensions:ExtensionsAny):
        self.m_includes:PyIncludes = PyIncludes(pyIncludesAny)
        self.m_extensions:Extensions = Extensions(extensions=extensions)

    def typeHint(self, containerClass:Optional[PyNameScope])->str:
        customType:Optional[str] = self.m_extensions.getValueOrNone(key=PY_TYPE_CUSTOM)
        if customType is not None: return customType
        return self._internalTypeHint(containerClass=containerClass)

    def declVar(self, writer:Writer, config:PyConfig, var:str, containerClass:Optional[PyNameScope], userDefinedDefault:PyRValueAny=None, provideWithDefaultIfNotSpecified:bool=False) -> None:
        '''! Generates a variable declaration like `var:type = default` 
             The default part is generated only if `userDefinedDefault` is not none.
             If `provideWithDefaultIfNotSpecified` it True, the type standard default is
             used if `userDefinedDefault` is None
        '''
        writer.writeRaw(text=f'{var}:{self.typeHint(containerClass=containerClass)}')
        defaultValue:PyRValueContainer = self.getDefaultValue(containerClass=containerClass, userDefinedDefault=userDefinedDefault) if provideWithDefaultIfNotSpecified else PyRValueContainer(pyValueAny=userDefinedDefault)
        if not defaultValue.empty():
            writer.writeRaw(text=f' = ')
            defaultValue.write(writer=writer, config=config)
        

    @abstractmethod
    def _internalTypeHint(self, containerClass:Optional[PyNameScope])->str:
        '''! Return the type hint for this type '''
        ...

    def __str__(self)->str: 
        assert(False)
        return "\n#error CALLED __str__ ON PyType\n"

    def setupModuleConfig(self, moduleConfig:PyModuleConfig) -> None:
        moduleConfig.m_pyIncludes.merge(self.m_includes)

    def getDefaultValue(self, containerClass:Optional[PyNameScope], userDefinedDefault:PyRValueAny)->PyRValueContainer:
        if userDefinedDefault is not None: 
            pyRValueContainer:PyRValueContainer = PyRValueContainer(pyValueAny=userDefinedDefault)
            if not pyRValueContainer.empty(): return pyRValueContainer
        return self._internalGetDefaultValue(containerClass=containerClass)

    @abstractmethod
    def _internalGetDefaultValue(self, containerClass:Optional[PyNameScope])->PyRValueContainer:
        '''! Returns the assignable default if none has been specified '''
        ...
    

PyTypeAny:TypeAlias = Union[PyType,PyNameScope,str]

# Contains the valid python native simple types and their default value
_PY_VALID_SIMPLE_TYPES:dict[str,str] = {
    'int': '0',
    'float': '0.0',
    'complex': '0 + 0j',
    'bool': 'False',
    'bytes': 'b""',
    'bytearray': 'bytearray()',
}

class PyTypeSimple(PyType):
    '''! Implements a simple type like `int`; must be in the list `_PY_VALID_SIMPLE_TYPES' '''
    def __init__(self, simpleType:str, pyIncludesAny:PyIncludesAny=None, extensions:ExtensionsAny = None, defaultValue:PyRValueAny=None):
        super().__init__(pyIncludesAny=pyIncludesAny, extensions=extensions)
        
        # Detect types like `dict[...]`, `list[...]`, etc.
        if defaultValue is None:
            matchResult:Optional[re.Match[str]] = re.search(r'^([a-z]+)', simpleType)
            if matchResult:
                typeName:str = matchResult[1]
                if typeName in ['dict', 'list', 'set']:
                    defaultValue = f'{typeName}()'

        if simpleType == 'str':
            print(f'[ERROR] Detected `PyTypeSimple(simpleType="str")`: use `PyTypeString()` instead')
            exit(1)
        #if not simpleType in _PY_VALID_SIMPLE_TYPES and defaultValue is None:
        #    print(f'[ERROR] Type `{simpleType}` is not known: provide with a `defaultValue`; known types are: {", ".join(_PY_VALID_SIMPLE_TYPES.keys())}')
        #    exit(1)
        self.m_simpleType:str = simpleType
        self.m_defaultValue:PyRValueAny = defaultValue

    def _internalTypeHint(self, containerClass:Optional[PyNameScope])->str:
        return self.m_simpleType

    def _internalGetDefaultValue(self, containerClass:Optional[PyNameScope])->PyRValueContainer:
        '''! Returns the assignable default if none has been specified '''
        return PyRValueContainer(_PY_VALID_SIMPLE_TYPES[self.m_simpleType])

class PyTypeNone(PyType):
    '''! Implements the type `None` '''
    def __init__(self, pyIncludesAny:PyIncludesAny=None, extensions:ExtensionsAny=None):
        super().__init__(pyIncludesAny=pyIncludesAny, extensions=extensions)

    def _internalTypeHint(self, containerClass:Optional[PyNameScope])->str:
        return 'None'

    def _internalGetDefaultValue(self, containerClass:Optional[PyNameScope])->PyRValueContainer:
        '''! Returns the assignable default if none has been specified '''
        return PyRValueContainer('None')

class PyTypeClass(PyType):
    '''! Implements a type that references a class generated by this generator '''
    def __init__(self, pyClass:PyNameScope, pyIncludesAny:PyIncludesAny=None, polymorphic:bool=False, extensions:ExtensionsAny = None):
        super().__init__(pyIncludesAny=pyIncludesAny, extensions=extensions)
        self.m_pyClass:PyNameScope = pyClass
        self.m_polymorphic:bool = polymorphic

    def _internalTypeHint(self, containerClass:Optional[PyNameScope])->str:
        if containerClass is not None:
            containerClassRef:PyNameScopeReferences = containerClass.getNameScopeReferences()
            containedClassRef:PyNameScopeReferences = self.m_pyClass.getNameScopeReferences()
            if containerClassRef.m_modulePath == containedClassRef.m_modulePath:
                return containedClassRef.m_namePath

        return self.m_pyClass.getPyQualifiedName(containerClass)

    def setupModuleConfig(self, moduleConfig:PyModuleConfig) -> None:
        super().setupModuleConfig(moduleConfig=moduleConfig)
        containerModuleRef:PyNameScopeReferences = moduleConfig.getNameScopeReferences()
        containedClassRef:PyNameScopeReferences = self.m_pyClass.getNameScopeReferences()
        containedClassRef.importThisIntoOther(other=containerModuleRef, otherImports=moduleConfig.m_pyIncludes)

    def _internalGetDefaultValue(self, containerClass:Optional[PyNameScope])->PyRValueContainer:
        '''! Returns the assignable default if none has been specified '''
        if isinstance(self.m_pyClass, PyEnumBase):
            return PyRValueContainer(f'{self.m_pyClass.getPyQualifiedName(otherScope=containerClass)}.{self.m_pyClass.getDefaultEntry().m_enumEntryName}')
        return PyRValueContainer(self._internalTypeHint(containerClass=containerClass)+'()')

class PyTypeVector(PyType):
    '''! Implements a `list` '''
    def __init__(self, containedType:PyTypeAny, pyIncludesAny:PyIncludesAny=None, extensions:ExtensionsAny = None):
        super().__init__(pyIncludesAny=pyIncludesAny, extensions=extensions)
        self.m_containedType:PyType = PyTypeFactory(containedType)

    def _internalTypeHint(self, containerClass:Optional[PyNameScope])->str:
        return f"list[{self.m_containedType.typeHint(containerClass=containerClass)}]"

    def setupModuleConfig(self, moduleConfig:PyModuleConfig) -> None:
        super().setupModuleConfig(moduleConfig=moduleConfig)
        self.m_containedType.setupModuleConfig(moduleConfig=moduleConfig)

    def _internalGetDefaultValue(self, containerClass:Optional[PyNameScope])->PyRValueContainer:
        return PyRValueContainer('list()')

class PyTypeOptional(PyType):
    '''! Implements a `Optional[]` '''
    def __init__(self, containedType:PyTypeAny, pyIncludesAny:PyIncludesAny=None, extensions:ExtensionsAny = None):
        super().__init__(pyIncludesAny=pyIncludesAny, extensions=extensions)
        self.m_containedType:PyType = PyTypeFactory(containedType)
        self.m_includes.addAny(('typing', 'Optional'))

    def _internalTypeHint(self, containerClass:Optional[PyNameScope])->str:
        return f"Optional[{self.m_containedType.typeHint(containerClass=containerClass)}]"

    def setupModuleConfig(self, moduleConfig:PyModuleConfig) -> None:
        super().setupModuleConfig(moduleConfig=moduleConfig)
        self.m_containedType.setupModuleConfig(moduleConfig=moduleConfig)

    def _internalGetDefaultValue(self, containerClass:Optional[PyNameScope])->PyRValueContainer:
        return PyRValueContainer('None')

class PyTypeMap(PyType):
    '''! Implements a `dict` '''
    def __init__(self, keyType:PyTypeAny, containedType:PyTypeAny, pyIncludesAny:PyIncludesAny=None, extensions:ExtensionsAny = None):
        super().__init__(pyIncludesAny=pyIncludesAny, extensions=extensions)
        self.m_keyType:PyType = PyTypeFactory(keyType)
        self.m_containedType:PyType = PyTypeFactory(containedType)

    def _internalTypeHint(self, containerClass:Optional[PyNameScope])->str:
        return f"dict[{self.m_keyType.typeHint(containerClass=containerClass)},{self.m_containedType.typeHint(containerClass=containerClass)}]"

    def setupModuleConfig(self, moduleConfig:PyModuleConfig) -> None:
        super().setupModuleConfig(moduleConfig=moduleConfig)
        self.m_keyType.setupModuleConfig(moduleConfig=moduleConfig)
        self.m_containedType.setupModuleConfig(moduleConfig=moduleConfig)

    def _internalGetDefaultValue(self, containerClass:Optional[PyNameScope])->PyRValueContainer:
        return PyRValueContainer('dict()')

class PyTypeString(PyType):
    '''! Implements a `str` '''
    def __init__(self, pyIncludesAny:PyIncludesAny=None, extensions:ExtensionsAny = None, defaultValue:Optional[str]=None):
        super().__init__(pyIncludesAny=pyIncludesAny, extensions=extensions)
        self.m_defaultValue:Optional[str] = defaultValue

    def _internalTypeHint(self, containerClass:Optional[PyNameScope])->str:
        return f"str"

    def _internalGetDefaultValue(self, containerClass:Optional[PyNameScope])->PyRValueContainer:
        if self.m_defaultValue is not None:
            return PyRValueContainer(f'"{strToPyStr(self.m_defaultValue)}"')
        return PyRValueContainer('""')

class PyTypeBinary(PyType):
    '''! Implements a `bytearray` '''
    def __init__(self, pyIncludesAny:PyIncludesAny=None, extensions:ExtensionsAny = None, defaultValue:Optional[str]=None):
        super().__init__(pyIncludesAny=pyIncludesAny, extensions=extensions)
        self.m_defaultValue:Optional[str] = defaultValue

    def _internalTypeHint(self, containerClass:Optional[PyNameScope])->str:
        return f"bytearray"

    def _internalGetDefaultValue(self, containerClass:Optional[PyNameScope])->PyRValueContainer:
        if self.m_defaultValue is not None:
            return PyRValueContainer(repr(self.m_defaultValue))
        return PyRValueContainer("bytearray(b'')")

def PyTypeFactory(pyTypeAny:PyTypeAny)->PyType:
    if isinstance(pyTypeAny, PyNameScope):
        return PyTypeClass(pyClass=pyTypeAny)
    elif isinstance(pyTypeAny, str):
        if pyTypeAny == 'str': return PyTypeString()
        return PyTypeSimple(simpleType=pyTypeAny)
    else:
        assert(isinstance(pyTypeAny, PyType))
        return pyTypeAny



